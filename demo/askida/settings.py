def env_dosyasini_oku(yol):
    """demo/.env dosyasındaki ANAHTAR=deger satırlarını ortam değişkenlerine ekler.

    Sırlar (SECRET_KEY, örnek kullanıcı şifresi) koda yazılmaz, bu dosyadan okunur.
    .env repoda yoktur (.gitignore), örneği .env.example dosyasındadır.
    Ek kütüphane gerekmesin diye küçük bir okuyucu yazdık.
    """
    if not yol.exists():
        return
    for satir in yol.read_text(encoding="utf-8").splitlines():
        satir = satir.strip()
        if not satir or satir.startswith("#") or "=" not in satir:
            continue
        anahtar, deger = satir.split("=", 1)
        os.environ.setdefault(anahtar.strip(), deger.strip())


env_dosyasini_oku(BASE_DIR / ".env")

